-- arabclue · Salla store link history for PDPL erasure / export (RB-S1)
--
-- Salla deliveries are logged in public.events under the Salla store id (events.merchant =
-- '<store id>'), not the merchant uuid. Disconnect (lib/salla/connect.ts unlinkSallaStore) clears
-- merchants.salla_merchant_id, and erasure / export only looked events up by the CURRENT store id —
-- so Disconnect followed by Delete account left all of the store's events (end-customer names,
-- emails, phone numbers, addresses) behind, and an export after Disconnect left them out.
--
-- 1. salla_store_links: one row per period a merchant held a store. Maintained by triggers on
--    merchants (every write path is covered: salla_link_store, claims, Disconnect, admin SQL).
--    When a merchant row is deleted its periods stay, without the merchant id, so the other
--    merchants' windows (below) stay bounded. Service role only.
-- 2. salla_merchant_event_windows(merchant): for each store the merchant has linked, the
--    [from_at, to_at) window of the store's events that belong to it (null = unbounded). A store's
--    events belong to whoever linked it last before them (events before the first link: the first
--    linker), so a store that was later linked by another merchant never exports or erases that
--    merchant's events. lib/merchant/pdpl.ts uses it for both erasure and export.
--
-- Disconnect semantics are unchanged. Re-runnable.

create table if not exists public.salla_store_links (
  id bigint generated by default as identity primary key,
  merchant_id uuid references public.merchants(id) on delete set null,
  salla_merchant_id text not null,
  linked_at timestamptz not null default now(),
  unlinked_at timestamptz,
  constraint salla_store_links_store_not_blank check (btrim(salla_merchant_id) <> ''),
  constraint salla_store_links_period check (unlinked_at is null or unlinked_at >= linked_at)
);

create index if not exists salla_store_links_store_idx on public.salla_store_links (salla_merchant_id, linked_at, id);
create index if not exists salla_store_links_merchant_idx on public.salla_store_links (merchant_id) where merchant_id is not null;
-- merchants.salla_merchant_id is unique and a merchant holds one store: at most one open period each
create unique index if not exists salla_store_links_open_store_key on public.salla_store_links (salla_merchant_id) where unlinked_at is null;
create unique index if not exists salla_store_links_open_merchant_key
  on public.salla_store_links (merchant_id) where unlinked_at is null and merchant_id is not null;

alter table public.salla_store_links enable row level security;
revoke all on table public.salla_store_links from anon, authenticated;
grant select, insert, update, delete on table public.salla_store_links to service_role;
revoke all on sequence public.salla_store_links_id_seq from anon, authenticated;
grant usage, select on sequence public.salla_store_links_id_seq to service_role;

-- ── trigger: record every change of merchants.salla_merchant_id ──────────────
-- clock_timestamp(), not now(): several link changes inside one transaction stay ordered.
create or replace function public.salla_store_links_track()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_at timestamptz := clock_timestamp();
begin
  if tg_op = 'DELETE' then
    -- BEFORE DELETE: close the open period while it still carries the merchant id
    update public.salla_store_links
       set unlinked_at = greatest(v_at, linked_at)
     where merchant_id = old.id and unlinked_at is null;
    return old;
  end if;

  if tg_op = 'UPDATE' and new.salla_merchant_id is not distinct from old.salla_merchant_id then
    return null;
  end if;

  -- close this merchant's open period, and any stale open period of the store it now holds
  update public.salla_store_links
     set unlinked_at = greatest(v_at, linked_at)
   where unlinked_at is null
     and (merchant_id = new.id or salla_merchant_id = new.salla_merchant_id);

  if nullif(btrim(new.salla_merchant_id), '') is not null then
    insert into public.salla_store_links (merchant_id, salla_merchant_id, linked_at)
    values (new.id, new.salla_merchant_id, v_at);
  end if;
  return null;
end;
$$;

revoke execute on function public.salla_store_links_track() from public, anon, authenticated;

drop trigger if exists merchants_salla_store_link on public.merchants;
create trigger merchants_salla_store_link
  after insert or update of salla_merchant_id on public.merchants
  for each row execute function public.salla_store_links_track();

drop trigger if exists merchants_salla_store_unlink on public.merchants;
create trigger merchants_salla_store_unlink
  before delete on public.merchants
  for each row execute function public.salla_store_links_track();

-- ── backfill: the stores merchants hold today ────────────────────────────────
insert into public.salla_store_links (merchant_id, salla_merchant_id, linked_at)
select m.id, m.salla_merchant_id, least(coalesce(m.installed_at, now()), now())
  from public.merchants m
 where nullif(btrim(m.salla_merchant_id), '') is not null
   and not exists (
     select 1 from public.salla_store_links l where l.merchant_id = m.id and l.unlinked_at is null
   )
   and not exists (
     select 1 from public.salla_store_links l where l.salla_merchant_id = m.salla_merchant_id and l.unlinked_at is null
   );

-- ── the event windows of a merchant ──────────────────────────────────────────
create or replace function public.salla_merchant_event_windows(p_merchant_id uuid)
returns table (salla_merchant_id text, from_at timestamptz, to_at timestamptz)
language sql
stable
security invoker
set search_path = public
as $$
  with periods as (
    select l.salla_merchant_id as store,
           l.merchant_id as owner,
           l.linked_at,
           row_number() over w as n,
           lead(l.linked_at) over w as next_linked_at
      from public.salla_store_links l
     where l.salla_merchant_id in (
       select s.salla_merchant_id from public.salla_store_links s where s.merchant_id = p_merchant_id
     )
    window w as (partition by l.salla_merchant_id order by l.linked_at, l.id)
  )
  select p.store,
         case when p.n = 1 then null else p.linked_at end,
         p.next_linked_at
    from periods p
   where p.owner = p_merchant_id
   order by p.store, p.linked_at
$$;

revoke execute on function public.salla_merchant_event_windows(uuid) from public, anon, authenticated;
grant execute on function public.salla_merchant_event_windows(uuid) to service_role;

